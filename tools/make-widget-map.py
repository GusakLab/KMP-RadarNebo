#!/usr/bin/env python3
"""
Writes app/android/src/main/res/drawable/widget_map.xml: Ukraine's oblasts as a vector drawable, the home screen
widget's map before its first data and in its preview. It draws them like WidgetMap.kt (same projection, colours
and stroke), so the preview looks like the widget; keep the constants below in step with it.

The outlines come from UkraineGeometry.kt. Points are rounded to whole units of a 360-wide viewport, and repeats
dropped, which keeps the file small at widget sizes.
Run: python3 -I tools/make-widget-map.py
"""
import math
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
GEOMETRY = ROOT / "core/src/commonMain/kotlin/com/gusak/lab/radarnebo/geo/UkraineGeometry.kt"
OUT = ROOT / "app/android/src/main/res/drawable/widget_map.xml"

# WidgetMap.kt
WEST, EAST, SOUTH, NORTH = 22.0, 40.4, 44.2, 52.5
LON_SCALE = math.cos(math.radians((SOUTH + NORTH) / 2))
LAND, BORDER = "#FF1E2A36", "#FF46607A"
WIDTH = 360
HEIGHT = round(WIDTH * (NORTH - SOUTH) / ((EAST - WEST) * LON_SCALE))


def outlines(source):
    """Each oblast's ring as (lon, lat) pairs, from the `val lonLat: FloatArray = floatArrayOf(...)` blocks."""
    for block in re.findall(r"val lonLat: FloatArray = floatArrayOf\((.*?)\)", source, re.S):
        numbers = [float(n) for n in re.findall(r"-?\d+\.\d+", block)]
        yield list(zip(numbers[0::2], numbers[1::2]))


def path_data(ring):
    points = []
    for lon, lat in ring:
        point = (round((lon - WEST) / (EAST - WEST) * WIDTH), round((NORTH - lat) / (NORTH - SOUTH) * HEIGHT))
        if not points or points[-1] != point:
            points.append(point)
    return "M" + "L".join(f"{x},{y}" for x, y in points) + "Z"


def main():
    rings = list(outlines(GEOMETRY.read_text()))
    assert len(rings) == 25, f"expected 25 oblasts, found {len(rings)}"
    paths = "\n".join(
        f'    <path\n        android:fillColor="{LAND}"\n        android:pathData="{path_data(ring)}"\n'
        f'        android:strokeColor="{BORDER}"\n        android:strokeWidth="0.75" />'
        for ring in rings
    )
    OUT.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/make-widget-map.py from UkraineGeometry.kt; don't edit by hand. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{WIDTH}dp"\n    android:height="{HEIGHT}dp"\n'
        f'    android:viewportWidth="{WIDTH}"\n    android:viewportHeight="{HEIGHT}">\n'
        f"{paths}\n</vector>\n"
    )
    print(f"{OUT.relative_to(ROOT)}: {len(rings)} oblasts, {OUT.stat().st_size // 1024} KiB")


if __name__ == "__main__":
    main()
